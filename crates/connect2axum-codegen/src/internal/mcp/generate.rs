const MCP_MODULE_SUFFIX: &str = "_mcp";
const TOOLS_FUNCTION_NAME: &str = "make_tools";

pub fn generate(request: &CodeGeneratorRequest) -> CodegenResult<CodeGeneratorResponse> {
    let options = McpOptions::parse(request.parameter.as_deref())?;
    let config = match options.config_path.as_deref() {
        Some(path) => McpConfigFile::from_path(path)?,
        None => McpConfigFile::default(),
    };
    let ir = build_ir(request)?;
    let catalog = build_catalog(&ir, &config)?;

    let files = catalog
        .files
        .iter()
        .map(|file| generate_file(&ir, file, &options))
        .collect::<CodegenResult<Vec<_>>>()?;

    Ok(CodeGeneratorResponse {
        file: files,
        ..Default::default()
    })
}

fn generate_file(
    ir: &DescriptorIr,
    file: &CatalogFile<'_>,
    options: &McpOptions,
) -> CodegenResult<CodeGeneratorResponseFile> {
    let generator = RustGenerator {
        options,
        resolver: TypeResolver::new(ir, &options.codegen),
    };

    ensure_unique_generated_identifiers(
        &format!("MCP file {}", file.file.name.as_ref()),
        file.services.iter().map(|service| {
            (
                service_module_name(service.service.name.as_ref()),
                format!("service {}", service.service.full_name.as_ref()),
            )
        }),
    )?;

    let modules = file
        .services
        .iter()
        .map(|service| generator.service_module(service))
        .collect::<CodegenResult<Vec<_>>>()?;
    let source = format_tokens(quote! { #(#modules)* })?;

    Ok(CodeGeneratorResponseFile {
        name: Some(output_file_name(file.file.name.as_ref())),
        content: Some(format!(
            "// @generated by connect2mcp.\n\
             // This file is generated from {}. Do not edit by hand.\n\n\
             {source}",
            file.file.name.as_ref()
        )),
        ..Default::default()
    })
}

fn output_file_name(proto_file_name: &str) -> String {
    let stem = proto_file_name
        .strip_suffix(".proto")
        .unwrap_or(proto_file_name);
    format!("{stem}.connect2mcp.rs")
}

struct RustGenerator<'a> {
    options: &'a McpOptions,
    resolver: TypeResolver<'a>,
}

impl RustGenerator<'_> {
    fn service_module(&self, service: &CatalogService<'_>) -> CodegenResult<TokenStream> {
        ensure_unique_generated_identifiers(
            &format!("MCP service {}", service.service.full_name.as_ref()),
            service
                .tools
                .iter()
                .map(|tool| {
                    (
                        self.resolver.method_fn_name(tool.method.name.as_ref()),
                        format!("method {}", tool.method.full_name.as_ref()),
                    )
                })
                .chain([(
                    TOOLS_FUNCTION_NAME.into(),
                    "the generated tool set function".to_owned(),
                )]),
        )?;

        let module_ident = parse_ident(
            &service_module_name(service.service.name.as_ref()),
            "generated MCP module",
        )?;
        let handlers = service
            .tools
            .iter()
            .map(|tool| self.handler_tokens(service, tool))
            .collect::<CodegenResult<Vec<_>>>()?;
        let make_tools = self.make_tools_tokens(service)?;

        Ok(quote! {
            /// Generated MCP tool handlers and tool set.
            pub mod #module_ident {
                use std::sync::Arc;

                #(#handlers)*

                #make_tools
            }
        })
    }

    fn handler_tokens(
        &self,
        service: &CatalogService<'_>,
        tool: &CatalogTool<'_>,
    ) -> CodegenResult<TokenStream> {
        let method = tool.method;
        let comments = comment_attrs(&method.comments);
        let service_trait = self.service_trait(service)?;
        let method_ident = parse_ident(
            self.resolver.method_fn_name(method.name.as_ref()).as_ref(),
            "MCP handler function",
        )?;
        let service_value = self.value_ident("service")?;
        let ctx_value = self.value_ident("ctx")?;
        let request_value = self.value_ident("request")?;
        let err_value = self.value_ident("err")?;
        let runtime = parse_path(
            self.options.codegen.runtime_module.as_ref(),
            "runtime module",
        )?;
        let mcp = parse_path(self.options.mcp_module.as_ref(), "MCP runtime module")?;
        let request_type = parse_type(
            self.resolver
                .owned_message_type(method.input_type.as_ref())?
                .as_str(),
            "method request type",
        )?;
        let request_view_type = parse_type(
            &format!(
                "{}<'static>",
                self.resolver
                    .view_message_type(method.input_type.as_ref())?
                    .as_str()
            ),
            "method request view type",
        )?;
        let output_type = parse_type(
            self.resolver
                .owned_message_type(method.output_type.as_ref())?
                .as_str(),
            "method output type",
        )?;

        Ok(quote! {
            #(#comments)*
            pub async fn #method_ident<S>(
                #service_value: Arc<S>,
                #ctx_value: ::connectrpc::RequestContext,
                #request_value: #request_type,
            ) -> #mcp::ToolResult
            where
                S: #service_trait + Send + Sync + 'static,
            {
                let #request_value = match #runtime::owned_view::<#request_view_type>(&#request_value) {
                    Ok(#request_value) => #request_value,
                    Err(#err_value) => return #mcp::error_result(#err_value),
                };
                let #request_value = ::connectrpc::ServiceRequest::from_parts(
                    #request_value.reborrow(),
                    #request_value.bytes(),
                );
                #mcp::tool_result::<#output_type, _>(
                    #service_value.#method_ident(#ctx_value, #request_value).await
                )
            }
        })
    }

    fn make_tools_tokens(&self, service: &CatalogService<'_>) -> CodegenResult<TokenStream> {
        let service_trait = self.service_trait(service)?;
        let mcp = parse_path(self.options.mcp_module.as_ref(), "MCP runtime module")?;
        let tools_ident = parse_ident(TOOLS_FUNCTION_NAME, "tool set function")?;
        let tools = service
            .tools
            .iter()
            .map(|tool| {
                let name = tool.name.as_ref();
                let schema = schema_literal(tool)?;
                let description = tool.description.as_deref().map(|description| {
                    quote! { .description(#description) }
                });
                let confirmation = tool
                    .requires_confirmation
                    .then(|| quote! { .requires_confirmation() });
                let method_ident = parse_ident(
                    self.resolver
                        .method_fn_name(tool.method.name.as_ref())
                        .as_ref(),
                    "MCP handler function",
                )?;
                Ok(quote! {
                    .tool(
                        #mcp::Tool::new(#name, #schema)#description #confirmation,
                        #method_ident::<S>,
                    )
                })
            })
            .collect::<CodegenResult<Vec<_>>>()?;

        Ok(quote! {
            pub fn #tools_ident<S>(service: Arc<S>) -> #mcp::Tools
            where
                S: #service_trait + Send + Sync + 'static,
            {
                #mcp::Tools::builder(service)
                    #(#tools)*
                    .build()
            }
        })
    }

    fn service_trait(&self, service: &CatalogService<'_>) -> CodegenResult<Path> {
        parse_path(
            self.resolver
                .connect_service_trait(service.service.full_name.as_ref())
                .as_str(),
            "Connect service trait",
        )
    }

    fn value_ident(&self, name: &str) -> CodegenResult<Ident> {
        parse_ident(
            self.resolver
                .value_ident(name, &self.options.codegen)
                .as_ref(),
            "generated binding",
        )
    }
}

/// Emits a tool's input schema as a pretty-printed raw string literal, so the
/// generated code shows readable JSON.
fn schema_literal(tool: &CatalogTool<'_>) -> CodegenResult<LitStr> {
    let mut json = String::new();
    write_json(&tool.input_schema, 0, &mut json);
    let hashes = "#".repeat(raw_string_hashes(&json));
    syn::parse_str(&format!("r{hashes}\"{json}\"{hashes}")).map_err(|err| {
        UniError::from_kind_context(
            CodegenErrKind::InvalidDescriptor,
            format!(
                "input schema literal for {} did not parse: {err}",
                tool.method.full_name.as_ref()
            ),
        )
    })
}

/// Schema keywords printed first, in this order, so each schema reads from
/// its kind to its details. Other keys, such as property names, follow in
/// sorted order.
const LEADING_KEYS: &[&str] = &[
    "$ref",
    "type",
    "format",
    "description",
    "enum",
    "properties",
    "items",
    "additionalProperties",
    "required",
    "$defs",
];

/// Pretty-prints JSON with two-space indentation, ordering object keys by
/// [`LEADING_KEYS`].
fn write_json(value: &Value, indent: usize, out: &mut String) {
    let pad = |depth: usize| "  ".repeat(depth);
    match value {
        Value::Object(object) if !object.is_empty() => {
            let mut keys = object.keys().collect::<Vec<_>>();
            keys.sort_by_key(|key| {
                (
                    LEADING_KEYS
                        .iter()
                        .position(|leading| leading == key)
                        .unwrap_or(LEADING_KEYS.len()),
                    key.as_str(),
                )
            });
            out.push_str("{\n");
            for (index, key) in keys.iter().enumerate() {
                out.push_str(&pad(indent + 1));
                out.push_str(&Value::String((*key).clone()).to_string());
                out.push_str(": ");
                write_json(&object[key.as_str()], indent + 1, out);
                if index + 1 < keys.len() {
                    out.push(',');
                }
                out.push('\n');
            }
            out.push_str(&pad(indent));
            out.push('}');
        }
        Value::Array(items) if !items.is_empty() => {
            out.push_str("[\n");
            for (index, item) in items.iter().enumerate() {
                out.push_str(&pad(indent + 1));
                write_json(item, indent + 1, out);
                if index + 1 < items.len() {
                    out.push(',');
                }
                out.push('\n');
            }
            out.push_str(&pad(indent));
            out.push(']');
        }
        _ => out.push_str(&value.to_string()),
    }
}

/// The fewest `#`s that let a raw string hold `text`: one more than the
/// longest run of `#` following a `"` in it.
fn raw_string_hashes(text: &str) -> usize {
    text.split('"')
        .skip(1)
        .map(|after_quote| after_quote.bytes().take_while(|byte| *byte == b'#').count())
        .max()
        .unwrap_or(0)
        + 1
}

fn comment_attrs(comments: &CommentSet) -> Vec<TokenStream> {
    comments
        .leading_detached
        .iter()
        .chain(comments.leading.iter())
        .flat_map(|comment| comment.lines())
        .map(str::trim_end)
        .filter(|line| !line.is_empty())
        .map(|line| quote! { #[doc = #line] })
        .collect()
}

fn service_module_name(service_name: &str) -> SharedStr {
    format!(
        "{}{MCP_MODULE_SUFFIX}",
        buffa_codegen::idents::escape_mod_ident(&service_name.to_snake_case())
    )
    .into_opt()
}

fn parse_ident(value: &str, context: &'static str) -> CodegenResult<Ident> {
    syn::parse_str(value).map_err(|err| {
        UniError::from_kind_context(
            CodegenErrKind::InvalidDescriptor,
            format!("{context} identifier {value:?} did not parse: {err}"),
        )
    })
}

fn parse_path(value: &str, context: &'static str) -> CodegenResult<Path> {
    syn::parse_str(value).map_err(|err| {
        UniError::from_kind_context(
            CodegenErrKind::InvalidDescriptor,
            format!("{context} path {value:?} did not parse: {err}"),
        )
    })
}

fn parse_type(value: &str, context: &'static str) -> CodegenResult<Type> {
    syn::parse_str(value).map_err(|err| {
        UniError::from_kind_context(
            CodegenErrKind::InvalidDescriptor,
            format!("{context} {value:?} did not parse: {err}"),
        )
    })
}

fn format_tokens(tokens: TokenStream) -> CodegenResult<String> {
    let file = syn::parse2(tokens.clone()).map_err(|err| {
        UniError::from_kind_context(
            CodegenErrKind::InvalidDescriptor,
            format!("generated Rust file did not parse: {err}\n{tokens}"),
        )
    })?;
    Ok(prettyplease::unparse(&file))
}

#[cfg(test)]
mod tests {
    use buffa::encoding::{Tag, WireType};
    use buffa::{MessageField, UnknownField, UnknownFieldData};
    use connectrpc_codegen::codegen::descriptor::{
        DescriptorProto, FieldDescriptorProto, FileDescriptorProto, MethodDescriptorProto,
        MethodOptions, ServiceDescriptorProto, SourceCodeInfo,
        field_descriptor_proto::{Label, Type},
        source_code_info::Location,
    };

    use serde_json::json;

    use super::{generate, raw_string_hashes, write_json};
    use crate::CodeGeneratorRequest;
    use crate::internal::http::HTTP_EXTENSION_NUMBER;

    fn string_field(name: &str, number: i32) -> FieldDescriptorProto {
        FieldDescriptorProto {
            name: Some(name.into()),
            number: Some(number),
            label: Some(Label::LABEL_OPTIONAL),
            r#type: Some(Type::TYPE_STRING),
            json_name: Some(name.into()),
            ..Default::default()
        }
    }

    fn message(name: &str, fields: Vec<FieldDescriptorProto>) -> DescriptorProto {
        DescriptorProto {
            name: Some(name.into()),
            field: fields,
            ..Default::default()
        }
    }

    fn method(name: &str, input: &str, output: &str) -> MethodDescriptorProto {
        MethodDescriptorProto {
            name: Some(name.into()),
            input_type: Some(input.into()),
            output_type: Some(output.into()),
            ..Default::default()
        }
    }

    fn file(
        name: &str,
        package: &str,
        services: Vec<ServiceDescriptorProto>,
    ) -> FileDescriptorProto {
        FileDescriptorProto {
            name: Some(name.into()),
            package: Some(package.into()),
            message_type: vec![
                message("Request", vec![string_field("name", 1)]),
                message("Reply", vec![string_field("message", 1)]),
            ],
            service: services,
            ..Default::default()
        }
    }

    fn service(name: &str, methods: Vec<MethodDescriptorProto>) -> ServiceDescriptorProto {
        ServiceDescriptorProto {
            name: Some(name.into()),
            method: methods,
            ..Default::default()
        }
    }

    fn generate_files(
        proto_file: Vec<FileDescriptorProto>,
        parameter: Option<&str>,
    ) -> Vec<(String, String)> {
        let request = CodeGeneratorRequest {
            file_to_generate: proto_file
                .iter()
                .filter_map(|file| file.name.clone())
                .collect(),
            proto_file,
            parameter: parameter.map(Into::into),
            ..Default::default()
        };
        generate(&request)
            .unwrap()
            .file
            .into_iter()
            .map(|file| (file.name.unwrap(), file.content.unwrap()))
            .collect()
    }

    #[test]
    fn generates_handlers_and_tool_sets_per_service() {
        let mut greeter = service(
            "GreeterService",
            vec![
                method("SayHello", ".hello.v1.Request", ".hello.v1.Reply"),
                method("SayBye", ".hello.v1.Request", ".hello.v1.Reply"),
            ],
        );
        greeter.method[1].server_streaming = Some(true);
        let mut proto = file(
            "hello/v1/hello.proto",
            "hello.v1",
            vec![
                greeter,
                service(
                    "AdminService",
                    vec![method("Reset", ".hello.v1.Request", ".hello.v1.Reply")],
                ),
            ],
        );
        proto.source_code_info = MessageField::some(SourceCodeInfo {
            location: vec![Location {
                path: vec![6, 0, 2, 0],
                leading_comments: Some(" Sends a greeting.\n".into()),
                ..Default::default()
            }],
            ..Default::default()
        });

        let files = generate_files(vec![proto], None);

        assert_eq!(files.len(), 1);
        let (name, content) = &files[0];
        assert_eq!(name, "hello/v1/hello.connect2mcp.rs");
        assert!(content.starts_with("// @generated by connect2mcp."));
        assert!(content.contains("pub mod greeter_service_mcp {"));
        assert!(content.contains("pub mod admin_service_mcp {"));
        assert!(content.contains("/// Sends a greeting."));
        assert!(content.contains("pub async fn say_hello<S>("));
        assert!(
            !content.contains("say_bye"),
            "streaming methods are skipped"
        );
        assert!(content.contains("request__: crate::proto::hello::v1::Request,"));
        assert!(content.contains("::connect2axum::owned_view::<"));
        assert!(content.contains("::connect2axum_mcp::tool_result::<"));
        assert!(content.contains("\"GreeterService_SayHello\""));
        assert!(content.contains(".description(\"Sends a greeting.\")"));
        assert!(content.contains("r#\"{\n  \"type\": \"object\","));
        assert!(content.contains("say_hello::<S>"));
        assert!(
            content
                .contains("S: crate::connect::hello::v1::GreeterService + Send + Sync + 'static")
        );
        syn::parse_file(content).expect("generated code parses");
    }

    #[test]
    fn honors_module_and_suffix_options() {
        let proto = file(
            "a.proto",
            "a.v1",
            vec![service(
                "Svc",
                vec![method("Do", ".a.v1.Request", ".a.v1.Reply")],
            )],
        );

        let files = generate_files(
            vec![proto],
            Some(
                "buffa_module=crate::p,connect_module=crate::c,runtime_module=crate::rt,mcp_module=crate::m,value_suffix=_x",
            ),
        );

        let content = &files[0].1;
        assert!(content.contains("request_x: crate::p::a::v1::Request"));
        assert!(content.contains("crate::rt::owned_view"));
        assert!(content.contains("-> crate::m::ToolResult"));
        assert!(content.contains("S: crate::c::a::v1::Svc"));
    }

    #[test]
    fn confirmed_tools_require_confirmation() {
        let proto = file(
            "a.proto",
            "a.v1",
            vec![service(
                "Svc",
                vec![
                    method("Get", ".a.v1.Request", ".a.v1.Reply"),
                    method("Delete", ".a.v1.Request", ".a.v1.Reply"),
                ],
            )],
        );
        let config =
            std::env::temp_dir().join(format!("connect2mcp-confirm-{}.yaml", std::process::id()));
        std::fs::write(&config, "confirm:\n  - a.v1.Svc.Delete\n").unwrap();

        let files = generate_files(vec![proto], Some(&format!("config={}", config.display())));
        std::fs::remove_file(&config).unwrap();

        let content = &files[0].1;
        assert_eq!(content.matches(".requires_confirmation()").count(), 1);
        let delete = content.find("\"Svc_Delete\"").unwrap();
        let confirmation = content.find(".requires_confirmation()").unwrap();
        assert!(confirmation > delete, "{content}");
        syn::parse_file(content).expect("generated code parses");
    }

    #[test]
    fn rpcs_without_http_bindings_are_tools_and_bound_ones_too() {
        let mut bound = method("Bound", ".a.v1.Request", ".a.v1.Reply");
        let mut rule = Vec::new();
        Tag::new(4, WireType::LengthDelimited).encode(&mut rule);
        buffa::types::encode_string("/bound", &mut rule);
        let mut options = MethodOptions::default();
        options.__buffa_unknown_fields.push(UnknownField {
            number: HTTP_EXTENSION_NUMBER,
            data: UnknownFieldData::LengthDelimited(rule),
        });
        bound.options = MessageField::some(options);
        let proto = file(
            "a.proto",
            "a.v1",
            vec![service(
                "Svc",
                vec![bound, method("Unbound", ".a.v1.Request", ".a.v1.Reply")],
            )],
        );

        let content = &generate_files(vec![proto], None)[0].1;

        assert!(content.contains("\"Svc_Bound\""));
        assert!(content.contains("\"Svc_Unbound\""));
    }

    #[test]
    fn files_without_tools_produce_no_output() {
        let mut streaming = method("Watch", ".a.v1.Request", ".a.v1.Reply");
        streaming.server_streaming = Some(true);
        let files = generate_files(
            vec![file(
                "a.proto",
                "a.v1",
                vec![service("Svc", vec![streaming])],
            )],
            None,
        );

        assert!(files.is_empty());
    }

    #[test]
    fn method_named_like_make_tools_is_an_identifier_collision() {
        let proto = file(
            "a.proto",
            "a.v1",
            vec![service(
                "Svc",
                vec![method("MakeTools", ".a.v1.Request", ".a.v1.Reply")],
            )],
        );
        let request = CodeGeneratorRequest {
            file_to_generate: vec!["a.proto".into()],
            proto_file: vec![proto],
            ..Default::default()
        };

        let err = generate(&request).unwrap_err();

        assert!(err.to_string().contains("make_tools"), "{err}");
    }

    #[test]
    fn schema_json_puts_keywords_first() {
        let mut out = String::new();
        write_json(
            &json!({
                "required": ["b"],
                "properties": { "b": { "type": "string" }, "a": {} },
                "type": "object",
                "description": "Doc."
            }),
            0,
            &mut out,
        );

        assert_eq!(
            out,
            "{\n  \"type\": \"object\",\n  \"description\": \"Doc.\",\n  \"properties\": {\n    \"a\": {},\n    \"b\": {\n      \"type\": \"string\"\n    }\n  },\n  \"required\": [\n    \"b\"\n  ]\n}"
        );
        let parsed: serde_json::Value = serde_json::from_str(&out).unwrap();
        assert_eq!(parsed["required"], json!(["b"]));
    }

    #[test]
    fn raw_string_hashes_avoid_terminators() {
        assert_eq!(raw_string_hashes(r#"{"a": 1}"#), 1);
        assert_eq!(raw_string_hashes(r##"{"a": "x"#"}"##), 2);
    }
}
